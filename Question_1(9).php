#Steps:
1. Open the XAMPP Control Panel.
2. Start the Apache and MySQL services by clicking the Start button beside each service.
3. Open a web browser such as Google Chrome or Microsoft Edge.
4. Enter the following URL in the address bar:
http://localhost/phpmyadmin
5. Press Enter to open phpMyAdmin.
6. Click New in the left navigation panel.
7. In the Database name field, enter:
TechnologyPortal.
8. Keep the default character set and collation, or select utf8mb4_general_ci.
9. Click Create.
10. Verify that the TechnologyPortal database appears in the left navigation panel